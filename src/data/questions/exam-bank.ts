export function buildQuestionFromSeed(seed: QuestionSeed): GeneratedQuestion {
  const topic = findTopicByChapter(seed.chapter);
  const spec = specForChapter(seed.chapter);
  const commandWords = extractCommandWords(seed.questionText);
  const base: GeneratedQuestion = {
    id: seed.id,
    title: seed.title,
    questionText: seed.questionText,
    questionType:
      topic.module === "stats"
        ? "statistics"
        : topic.module === "mechanics"
          ? "mechanics"
          : "pure",
    difficulty: seed.difficulty,
    topics: [topic],
    marks: seed.marks,
    examBoard: "Edexcel",
    specification: "A-Level GCE",
    year: "generated",
    source: "real-exam-inspired",
    answer: seed.answer,
    method: seed.method,
    steps: seed.steps.map((s, i) => ({
      id: `s${i + 1}`,
      explanation: s.explanation,
      working: s.working,
    })),
    formulaSheetAllowed: true,
    calculatorAllowed: seed.calculator,
    chapter: topic.chapter,
    subChapter: topic.section,
    tags: [...seed.tags, seed.paperStyle],
    specPoint: seed.specPoint || defaultSpecPoint(seed.chapter),
    theme: spec.theme,
    commandWords,
    precision: extractPrecision(seed.questionText, seed.answer),
    lds: seed.lds,
    foundation: seed.foundation,
    verified: true,
    metadata: {
      solvability: {
        isSolvable: true,
        issues: [],
        confidence: 0.99,
        estimatedDifficulty: seed.difficulty,
        prerequisites: [topic.name],
      },
      generationModel: "exam-bank",
      createdAt: new Date(),
    },
  };
  return { ...base, markScheme: seed.markScheme || markSchemeFor(base) };
}

